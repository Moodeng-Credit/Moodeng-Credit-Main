export const translations: Record<LocaleCode, Record<TranslationKey, string>> = {
   en: englishTranslations,
   fil: filipinoTranslations,
   id: indonesianTranslations,
   th: thaiTranslations,
   vi: vietnameseTranslations
};

export function resolveLocaleCode(value?: string | null): LocaleCode | null {
   if (!value) return null;

   const normalized = value.toLowerCase().replace('_', '-');
   const primarySubtag = normalized.split('-')[0];

   if (primarySubtag === 'en') return 'en';
   if (primarySubtag === 'fil' || primarySubtag === 'tl' || normalized === 'tagalog') return 'fil';
   if (primarySubtag === 'id' || normalized === 'indonesian' || normalized === 'bahasa-indonesia') return 'id';
   if (primarySubtag === 'th' || normalized === 'thai') return 'th';
   if (primarySubtag === 'vi' || normalized === 'vietnamese' || normalized === 'tieng-viet') return 'vi';

   return null;
}

export function pickInitialLocale({
   storedLocale,
   browserLocales = []
}: {
   storedLocale?: string | null;
   browserLocales?: readonly string[];
}): LocaleCode {
   const stored = resolveLocaleCode(storedLocale);
   if (stored) return stored;

   for (const browserLocale of browserLocales) {
      const resolved = resolveLocaleCode(browserLocale);
      if (resolved) return resolved;
   }

   return 'en';
}

export function translate(locale: LocaleCode, key: TranslationKey, params?: Record<string, string | number>) {
   const template = translations[locale]?.[key] ?? translations.en[key] ?? key;

   if (!params) return template;

   return template.replace(/\{(\w+)\}/g, (match, paramName: string) =>
      Object.prototype.hasOwnProperty.call(params, paramName) ? String(params[paramName]) : match
   );
}
