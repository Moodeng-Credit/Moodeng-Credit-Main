#!/usr/bin/env node
/**
 * build-support-knowledge.mjs
 *
 * Assembles the support chatbot's knowledge base from the SAME data the app
 * already renders, so there is ONE source of truth and no drift:
 *
 *   src/views/support/data/faqs.ts        (public FAQ)
 *   src/views/account/data/accountFaqs.ts (in-account FAQ: shared/borrower/lender)
 *   src/views/support/data/guides.ts      (help-center guides, English)
 *   tools/support-knowledge/troubleshooting.md  (hand-maintained real-chat fixes)
 *
 * Output:  supabase/functions/support-chat/knowledge.md
 *
 * Run it whenever the FAQ/guide content or the troubleshooting file changes:
 *   node tools/build-support-knowledge.mjs
 *
 * Requires Node >= 22.6 (uses native TypeScript type-stripping to import the
 * .ts data files directly — they are pure data with no imports).
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repo = resolve(__dirname, '..');
const r = (p) => resolve(repo, p);

const OUT = r('supabase/functions/support-chat/knowledge.md');

const { FAQS } = await import(r('src/views/support/data/faqs.ts'));
const { SHARED_FAQS, BORROWER_FAQS, LENDER_FAQS } = await import(r('src/views/account/data/accountFaqs.ts'));
const { GUIDES } = await import(r('src/views/support/data/guides.ts'));
const troubleshooting = await readFile(r('tools/support-knowledge/troubleshooting.md'), 'utf8');

const out = [];
const push = (s = '') => out.push(s);

push('# Moodeng Credit — Support Knowledge Base');
push();
push('<!-- AUTO-GENERATED by tools/build-support-knowledge.mjs — DO NOT EDIT BY HAND.');
push('     Edit the source FAQ/guide data files, or tools/support-knowledge/troubleshooting.md,');
push('     then re-run: node tools/build-support-knowledge.mjs -->');
push();
push('This is everything the support assistant knows about Moodeng Credit. Answer only');
push('from what is written here. If the answer is not here, say you are not sure and offer');
push('to connect the user with the team — never guess about money, wallets, or verification.');
push();

const faqSection = (title, items) => {
   push(`## ${title}`);
   push();
   for (const it of items) {
      push(`### ${it.question}`);
      push();
      push(it.answer.trim());
      push();
   }
};

faqSection('General FAQ', FAQS);
faqSection('Account FAQ — everyone', SHARED_FAQS);
faqSection('Account FAQ — borrowers', BORROWER_FAQS);
faqSection('Account FAQ — lenders', LENDER_FAQS);

push('## Step-by-step Guides');
push();
for (const g of GUIDES) {
   push(`### ${g.title}`);
   push();
   push(g.body.trim());
   push();
}

// The hand-maintained troubleshooting file already has its own top-level heading;
// strip its HTML editing-note comment so it doesn't leak build instructions to the model.
push('---');
push();
push(troubleshooting.replace(/<!--[\s\S]*?-->/g, '').replace(/\n{3,}/g, '\n\n').trim());
push();

const text = out.join('\n');
await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, text, 'utf8');

// Also emit a TS module the edge function imports STATICALLY. Supabase's bundler
// only ships files reachable through imports, so a runtime Deno.readTextFile of
// the .md finds nothing once deployed. JSON.stringify keeps backticks, ${...},
// and every other character safe inside the string literal.
const OUT_TS = r('supabase/functions/support-chat/knowledge.ts');
await writeFile(
   OUT_TS,
   `// AUTO-GENERATED by tools/build-support-knowledge.mjs — DO NOT EDIT BY HAND.\nexport const KNOWLEDGE = ${JSON.stringify(text)};\n`,
   'utf8'
);
console.log(`✓ Wrote ${OUT_TS}`);

const words = text.trim().split(/\s+/).length;
const approxTokens = Math.round(text.length / 4);
console.log(`✓ Wrote ${OUT}`);
console.log(`  ${FAQS.length} general FAQ, ${SHARED_FAQS.length}+${BORROWER_FAQS.length}+${LENDER_FAQS.length} account FAQ, ${GUIDES.length} guides + troubleshooting`);
console.log(`  ${text.length.toLocaleString()} chars · ~${words.toLocaleString()} words · ~${approxTokens.toLocaleString()} tokens`);
