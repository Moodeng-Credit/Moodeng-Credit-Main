#!/bin/sh
# Bundles the Messenger booking bot's conversation (supabase/functions/_shared/bookingBot.ts) into the
# plain JS file the booking-bot test page loads (moodeng.app/booking-bot-test). Re-run after editing
# bookingBot.ts, and commit both files. Needs Deno 2.4+ (`deno bundle`).
set -e
cd "$(dirname "$0")/.."
OUT=public/design/booking-bot-test/bookingBot.js
deno bundle --no-lock --platform browser --format esm -o "$OUT.tmp" supabase/functions/_shared/bookingBot.ts
{ echo '// GENERATED by scripts/build-booking-bot.sh from supabase/functions/_shared/bookingBot.ts — do not edit.'; cat "$OUT.tmp"; } > "$OUT"
rm "$OUT.tmp"
echo "Wrote $OUT"
